/** 轻量模型：复杂任务容易做不好，要主动说 */
export const LIGHT_MODEL = /luna|mini|lite|flash|haiku|nano|small|turbo|\b(?:7|8)b\b/i;

/**
 * @param {string} text  本轮请求
 * @param {{ light?: boolean, care?: boolean, feeling?: boolean, model?: string }} o
 * @returns {{ scene: string, note: string }}
 */
export function answerStyle(text, { light = false, care = false, feeling = false, model = '' } = {}) {
  const value = String(text || '').slice(0, 600);
  const lines = [];
  let scene = 'general';
  if (light) {
    scene = 'chat';
    lines.push('语气轻松、简短，可以带点俏皮；一两句话，不列清单，不每句问“还需要什么帮助”。');
  } else if (!care && !feeling) {
    const hit = SCENES.find((item) => item.test.test(value));
    if (hit) {
      scene = hit.id;
      lines.push(`语气：${hit.tone}回答顺序：${hit.order}`);
    } else lines.push('回答顺序：先说用户最想知道的那句话，再给依据，最后给下一步；限制和提醒只在最后说一次。');
  } else scene = care ? 'care' : 'feeling';
  lines.push('称呼按记忆里用户喜欢的来，不知道就不称呼；不装作有人的经历和感受。');
  // 模型名已由 modelNote（“你在用的模型”）告诉模型；这里只补轻量模型要主动说明这一条
  if (model && LIGHT_MODEL.test(model))
    lines.push(`本轮的 ${String(model).slice(0, 60)} 是轻量模型：复杂任务（画架构图、写长方案、多步排查）失败或效果差时，主动告诉用户当前是轻量模型，建议换主力模型再试。`);
  return { scene, note: lines.join('\n') };
}
