/** 按任务和标题判断文种（判断不出返回 null） */
const ORDER = ['official', 'minutes', 'speech', 'proposal', 'research', 'summary', 'plan']; // 具体的先判断
export function detectGenre(...texts) {
  const t = texts.filter(Boolean).join(' ');
  return ORDER.map((id) => GENRES.find((g) => g.id === id)).find((g) => g.match.test(t)) ?? null;
}

/** 列大纲时附上的文种结构 */
export function genreHint(genre) {
  return genre ? `\n\n这类文档（${genre.name}）的标准结构，请按此组织（可按用户要求增减）：\n${genre.structure}` : '';
}
