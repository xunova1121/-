/** 只识别明确的确定性时间/换算请求，新闻日期、天气与生成任务不因此裁掉工具。 */
export function timeCalculationRequest(text = '') {
  return /(?:\d+|[一二三四五六七八九十两]+)\s*(?:小时|分钟|天)(?:以)?[前后].{0,8}(?:几点|时间|几号|日期|星期)|(?:距离|距|到).{0,15}(?:春节|元旦|清明|劳动节|端午|中秋|国庆).{0,8}(?:多久|几天|多少天)|下周[一二三四五六日天].{0,6}(?:几号|日期|哪天)|(?:纽约|伦敦|东京|洛杉矶|悉尼|巴黎|迪拜|新加坡).{0,8}(?:现在|当前).{0,3}几点|(?:有|加|减|多少|几个).{0,5}工作日|农历.{0,12}(?:公历|阳历)|(?:公历|阳历).{0,12}农历|(?:几岁|周岁|虚岁)/.test(text);
}

export function addedCalculationRequest(text = '') {
  return timeCalculationRequest(text) || /贷款|房贷|月供|等额本[息金]|同比|环比|平均数|中位数/.test(text) && /\d/.test(text) || /\d+(?:\.\d+)?\s*(?:斤|两|亩|华氏|摄氏|英里|英尺|英寸|加仑|磅).{0,8}(?:等于|多少|换算|转换)/.test(text);
}
