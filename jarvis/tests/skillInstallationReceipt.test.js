import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, expect, it } from 'vitest';
import { useBackend } from '../src/agent/store.js';
import { createFileStore } from '../server/fileStore.mjs';
import { createTools } from '../src/agent/tools.js';
import * as ws from '../src/agent/workspace.js';
import * as packs from '../src/agent/skillPacks.js';
let directory;
beforeEach(() => { directory = fs.mkdtempSync(path.join(os.tmpdir(), 'skill-install-receipt-')); useBackend(createFileStore(directory)); });
afterEach(() => { useBackend(null); fs.rmSync(directory, { recursive: true, force: true }); });
const source = version => `---\nname: fixture-receipt\nversion: ${version}\ndescription: 虚构版本验收\n---\n\n# 版本${version}\n这里是实际已安装说明，不是草稿。`;
it('修改草稿不冒充安装，重装后读到真实新批次和版本，读取不冒称执行成功', async () => {
  const tools = createTools({});
  const install = tools.find(t => t.name === 'install_skill');
  const use = tools.find(t => t.name === 'use_skill');
  await ws.write('skills-draft/fixture/SKILL.md', source('1.0'));
  const receipt1 = await install.run({ path: 'skills-draft/fixture' });
  const first = await packs.get('fixture-receipt');
  expect(receipt1).toContain(first.installationId);
  expect(receipt1).toContain('已从安装库读回');
  await ws.write('skills-draft/fixture/SKILL.md', source('2.0'));
  expect(await use.run({ name: 'fixture-receipt' })).toContain('声明版本：1.0');
  const receipt2 = await install.run({ path: 'skills-draft/fixture' });
  const second = await packs.get('fixture-receipt');
  expect(second.installationId).not.toBe(first.installationId);
  expect(second.previousInstallationId).toBe(first.installationId);
  expect(receipt2).toContain('声明版本：2.0');
  expect(await use.run({ name: 'fixture-receipt' })).toContain('本次仅读取已安装说明');
});
it('停用后重装保留停用状态，安装不绕过原用户确认机制', async () => {
  await packs.installFromText(source('1.0'));
  await packs.setEnabled('fixture-receipt', false);
  await ws.write('skills-draft/fixture/SKILL.md', source('2.0'));
  const install = createTools({}).find(t => t.name === 'install_skill');
  expect(install.approval({ path: 'skills-draft/fixture' }).key).toBe('skill-install');
  expect(await install.run({ path: 'skills-draft/fixture' })).toContain('仍被用户停用');
  expect((await packs.get('fixture-receipt')).enabled).toBe(false);
});
