import { it, expect, vi, beforeEach, afterEach } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createFileStore } from '../server/fileStore.mjs';
import { useBackend } from '../src/agent/store.js';
import * as ws from '../src/agent/workspace.js';
import { ARCHITECTURE_CONTENT_EXAMPLE } from '../src/agent/architectureContentContract.js';
import { createArchitectureWorkflowTool } from '../src/agent/architectureWorkflow.js';
import { executeToolCalls } from '../src/agent/agentToolExecution.js';
import { createExecutionReview } from '../src/agent/executionReview.js';
import { createDiagramRecovery } from '../src/agent/diagramRecovery.js';
let root;
beforeEach(async () => { root = fs.mkdtempSync(path.join(os.tmpdir(), 'workflow-review-')); useBackend(createFileStore(root)); await ws.write('虚构原文.md', '示范事项受理后办理。'); });
afterEach(() => { useBackend(null); fs.rmSync(root, { recursive: true, force: true }); });
const args = { files: ['虚构原文.md'], request: '制作总体架构', directory: '交付' };
const stateOf = async jobPath => JSON.parse(await ws.readText(jobPath));
it('审查格式失败留在review，沿用相同底稿只恢复一次；业务明确否决才回内容修改', async () => {
  let contentCalls = 0, reviewCalls = 0;
  const llm = vi.fn(async request => {
    if (request.system.includes('你负责业务理解')) { contentCalls++; return JSON.stringify(ARCHITECTURE_CONTENT_EXAMPLE); }
    reviewCalls++;
    return reviewCalls === 1 ? '{"passed":"true","issues":[]}' : '{"passed":false,"issues":[{"target":"entity:receive","kind":"classification","detail":"需按原文核对活动职责"}]}';
  });
  const tool = createArchitectureWorkflowTool({ llm });
  const first = JSON.parse(await tool.run(args));
  expect(first).toMatchObject({ stage: 'review', ready: false, attemptsRemaining: 2 });
  const before = await stateOf(first.jobPath), content = await ws.readText(before.contentPath), original = await ws.readText(before.architecturePath);
  const second = JSON.parse(await tool.run({ jobPath: first.jobPath }));
  expect(second).toMatchObject({ stage: 'content', ready: false, attemptsRemaining: 2 });
  expect(contentCalls).toBe(1); expect(reviewCalls).toBe(2);
  expect(await ws.readText(before.contentPath)).toBe(content);
  expect(await ws.readText(before.architecturePath)).toBe(original);
  expect((await stateOf(first.jobPath)).lastError.issues[0].target).toBe('entity:receive');
});
it('审查持续技术失败只恢复一次，不把已通过结构检查的内容重写；多次续接不新增收费', async () => {
  const llm = vi.fn(async request => request.system.includes('你负责业务理解') ? JSON.stringify(ARCHITECTURE_CONTENT_EXAMPLE) : '不是JSON');
  const tool = createArchitectureWorkflowTool({ llm });
  const first = JSON.parse(await tool.run(args)), before = await stateOf(first.jobPath);
  const content = await ws.readText(before.contentPath), original = await ws.readText(before.architecturePath);
  await expect(tool.run({ jobPath: first.jobPath })).rejects.toMatchObject({ terminal: true, diagnostics: [{ stage: 'review' }] });
  const ended = await stateOf(first.jobPath);
  expect(ended.stage).toBe('review'); expect(ended.attempts).toBe(1);
  expect(ended.lastError.code).toBe('ARCHITECTURE_REVIEW_FORMAT');
  expect(ended.terminalFailure).toEqual({ phase: 'review', code: 'REVIEW_RECOVERY_EXHAUSTED' });
  for (let i = 0; i < 2; i++) await expect(tool.run({ jobPath: first.jobPath })).rejects.toHaveProperty('terminal', true);
  expect(llm).toHaveBeenCalledTimes(3);
  expect(await ws.readText(before.contentPath)).toBe(content); expect(await ws.readText(before.architecturePath)).toBe(original);
  const replies = (await ws.list('文档检查/架构审查回复')).filter(file => file.path.endsWith('.txt'));
  expect(replies).toHaveLength(2);
  for (const file of replies) expect(await ws.readText(file.path)).toBe('不是JSON');
});
it('内容额度耗尽保留真实字段和三份诊断，执行器当场停止同批后续动作', async () => {
  const content = structuredClone(ARCHITECTURE_CONTENT_EXAMPLE);
  content.relations[0].type = 'dataflow'; content.entities[0].outputs = [];
  const llm = vi.fn(async () => JSON.stringify(content)), tool = createArchitectureWorkflowTool({ llm });
  await expect(tool.run(args)).rejects.toHaveProperty('code', 'ARCHITECTURE_PLAN');
  const jobPath = (await ws.list('文档检查/架构任务')).find(file => !file.path.includes('.content.')).path;
  const effect = { name: 'side_effect', input_schema: { properties: {} }, run: vi.fn(async () => 'done') };
  const ctx = { loader: { get: name => name === 'build_architecture' ? tool : effect }, emit: vi.fn(), seen: new Map(), review: createExecutionReview('制作架构图'), webTools: new Set(), parallelSafe: new Set(), retrieval: { extensive: true, consume: vi.fn() }, diagramRecovery: createDiagramRecovery() };
  const call = { id: 'resume', name: 'build_architecture', args: { jobPath } };
  await executeToolCalls([call], ctx);
  const final = await executeToolCalls([call, { id: 'later', name: 'side_effect', args: {} }], ctx);
  expect(final[0].recoveryStop).toContain('已达3次');
  expect(final[0].output).toContain('本任务不再自动续跑');
  expect(final[0].output).not.toContain('仅用build_architecture({jobPath})继续');
  expect(effect.run).not.toHaveBeenCalled(); expect(llm).toHaveBeenCalledTimes(3);
  const state = await stateOf(jobPath), snapshot = JSON.stringify(state);
  expect(state.lastError).toMatchObject({ code: 'ARCHITECTURE_PLAN', diagnostics: [{ field: 'relations[0]', stage: 'review' }] });
  const diagnostics = await ws.list('文档检查/架构诊断'); expect(diagnostics).toHaveLength(3);
  await expect(tool.run({ jobPath })).rejects.toHaveProperty('terminal', true);
  expect(JSON.stringify(await stateOf(jobPath))).toBe(snapshot);
  expect((await ws.list('文档检查/架构诊断')).length).toBe(3);
});
it('交付目录尾斜杠无损规范化，非法绝对/跳转/内部空段仍拒绝', async () => {
  const llm = vi.fn(async request => request.system.includes('你负责业务理解') ? JSON.stringify(ARCHITECTURE_CONTENT_EXAMPLE) : '{"passed":false,"issues":[]}');
  const tool = createArchitectureWorkflowTool({ llm });
  const result = JSON.parse(await tool.run({ ...args, directory: '交付/' }));
  expect((await stateOf(result.jobPath)).directory).toBe('交付');
  const calls = llm.mock.calls.length;
  for (const directory of ['/', '/absolute', 'a/../b/', 'a//b/', 'a\\b']) await expect(tool.run({ ...args, directory })).rejects.toThrow('相对交付目录');
  expect(llm).toHaveBeenCalledTimes(calls);
});
