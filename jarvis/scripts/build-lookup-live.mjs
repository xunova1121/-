/** 将同一套解析器打成国内服务器可单文件运行的只读探测脚本；无运行时npm安装。 */
import { build } from 'esbuild';
import fs from 'node:fs/promises';
const check = process.argv.includes('--check');
const result = await build({ entryPoints: ['evals/lookup-live-entry.mjs'], outfile: 'evals/lookup-live.mjs', write: !check, bundle: true, platform: 'node', target: 'node22', format: 'esm', banner: { js: '// Generated by node scripts/build-lookup-live.mjs; shared application parsers, no credentials.' } });
if (check && await fs.readFile('evals/lookup-live.mjs', 'utf8') !== result.outputFiles[0].text) throw Error('国内实测脚本与共享解析器不一致，请重建脚本后重新实测');
console.log(check ? '国内实测单文件与共享源码一致' : '已生成无外部运行依赖的evals/lookup-live.mjs');
