/**
 * 接缝：标着「连续动作」的两镜之间，怎么让画面真的接上。
 *
 * ════════ 为什么这几句话要单独放一个文件 ════════
 *
 * 这是这个项目里**最容易被说错**的一件事，而且已经说错过：
 * 手机端那张卡片上写的是「标成连续动作会把上一镜的末帧锁成下一镜的首帧」——
 * 那句话描述的是 tail 模式，而默认跑的是 lock。用户照着那句话去看成片，
 * 看到"这一段的第一帧根本不是上一段的最后一帧"，得出的结论只能是"坏了"。
 *
 * 实际上两种模式**看起来完全不一样**：
 *
 *   lock（首尾帧，默认）
 *     本镜的图当首帧、**下一镜的图当末帧**，两头都是你审过的图。
 *     ⚠ 每一段视频**仍然是从自己那张图开始的** —— 接缝是靠逼上一段
 *       "结束在下一镜那张图上"做出来的，也就是说**做在上一镜身上**。
 *       选了 lock 又去看"这一段的首帧是不是上一段的尾帧"，答案永远是否，
 *       而那不是没生效。
 *
 *   tail（接住真实末帧）
 *     把上一段视频**真的抠一帧出来**，当这一镜的首帧。
 *     这一段的第一帧才真的等于上一段的最后一帧。
 *     所有厂商都收首帧图，所以不挑厂商；代价是只钉住起点，
 *     结尾由模型发挥，误差沿着链累积。
 *
 * 三处要用同一份措辞：设置里那个下拉、手机端那张卡片、出视频时的说明。
 * 各写各的话，迟早会有一处和引擎的实际行为对不上 —— 上面那个 bug 就是这么来的。
 *
 * ⚠ 这个文件要**原样发给浏览器**（/seam.js），所以必须保持零依赖。
 */

export const SEAM_MODES = [
  {
    id: 'lock',
    label: '首尾帧',
    /** 下拉框里那一行 */
    option: '首尾帧 —— 本镜的图当首帧、下一镜的图当末帧。两头都是你审过的图，要厂商收末帧',
    /** 一句话说清楚"会看到什么" —— 这句最要紧，它决定用户会不会误判成故障 */
    how: '本镜的图当首帧、**下一镜的图当末帧**。'
      + '⚠ 每一段仍然是从自己那张图开始的 —— 接缝做在**上一镜**身上（逼它结束在下一镜那张图上）。'
      + '所以别去看"这一段的首帧是不是上一段的尾帧"，那永远是否，而且不代表没生效。',
    needsVendor: true
  },
  {
    id: 'tail',
    label: '接住真实末帧',
    option: '接住真实末帧 —— 上一段的最后一帧当首帧。所有厂商都支持，但误差会沿着链累积',
    how: '把上一段视频**真的抠一帧出来**当这一镜的首帧 —— 这一段的第一帧就等于上一段的最后一帧。'
      + '所有厂商都收首帧图，不挑厂商；代价是只钉住起点，结尾由模型发挥，误差沿着链累积。',
    needsVendor: false
  },
  {
    id: 'off',
    label: '关掉',
    option: '关掉 —— 只靠提示词衔接',
    how: '什么都不做，只靠提示词衔接 —— 接缝会跳。',
    needsVendor: false
  }
];

const BY_ID = new Map(SEAM_MODES.map((m) => [m.id, m]));

/** 不认识的值一律当默认（lock）。设置文件是可以手改的 */
export function modeOf(id) {
  return BY_ID.get(id) || BY_ID.get('lock');
}

/**
 * 「标成连续动作会发生什么」——**按当前模式**说。
 *
 * 不带模式地泛泛说一句，就是上面那个 bug 的来源。
 */
export function howItWorks(seamMode) {
  const m = modeOf(seamMode);
  return `当前接缝模式是「${m.label}」：${m.how}`;
}

/**
 * 无论哪一种模式，都只在标着「连续动作」的两镜之间发生。
 *
 * link 不会被自动推断成 continuous —— 一处都没标的项目上接缝一处也不做，
 * 这是最常见的"接缝没生效"。这句话必须跟着上面那句一起出现。
 */
export const ONLY_ON_CONTINUOUS =
  '⚠ 接缝只在标着「连续动作」的两镜之间发生。一处都没标的话，接缝一处也不会做。';
